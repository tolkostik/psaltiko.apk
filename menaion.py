def search_name(q):
    """Πότε γιορτάζει ένα όνομα. [(μήνας, ημέρα, όνομα)] + κινητές."""
    import unicodedata

    def fold(t):
        t = unicodedata.normalize("NFD", t.lower())
        return "".join(c for c in t if unicodedata.category(c) != "Mn").replace("ς", "σ")
    q = fold(q.strip())
    if len(q) < 2:
        return []
    out = [(m, d, n) for (m, d), ns in NAMES.items() for n in ns if fold(n).startswith(q)]
    movable = {"Αναστάσιος": "Το Πάσχα", "Αναστασία": "Το Πάσχα (ή 22/12)", "Λάμπρος": "Το Πάσχα",
               "Λαμπρινή": "Το Πάσχα", "Πασχάλης": "Το Πάσχα", "Ζωή": "Ζωοδόχου Πηγής", "Πηγή": "Ζωοδόχου Πηγής",
               "Ζήσης": "Ζωοδόχου Πηγής", "Θωμάς": "Κυριακή του Θωμά (ή 6/10)", "Γεώργιος": "23/4 (ή Δευτέρα του Πάσχα)",
               "Γεωργία": "23/4 (ή Δευτέρα του Πάσχα)", "Γιώργος": "23/4 (ή Δευτέρα του Πάσχα)",
               "Τριαντάφυλλος": "Αγίου Πνεύματος", "Αναλήψιος": "Ανάληψη"}

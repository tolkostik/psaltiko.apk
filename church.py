def easter(year):
    return FC.orthodox_easter(year)


def _paschal_year_start(d):
    """Το Πάσχα της «λειτουργικής χρονιάς» στην οποία ανήκει η ημέρα (από Θωμά έως Θωμά)."""
    E = easter(d.year)
    return E if d >= E else easter(d.year - 1)


def week_sunday(d):
    """Η Κυριακή που «κυβερνά» την ημέρα: η εβδομάδα ξεκινά από τον Εσπερινό του Σαββάτου."""
    return d - td(days=(d.weekday() + 1) % 7)


def tone(d):
    """Ήχος της εβδομάδας (1-8) ή None στη Μεγάλη Εβδομάδα και τη Διακαινήσιμο."""
    E = easter(d.year)
    if E - td(days=7) <= d <= E + td(days=6):
        if E <= d <= E + td(days=6):                 # Διακαινήσιμος: κάθε ημέρα άλλος ήχος (ο Βαρύς παραλείπεται)
            return [1, 2, 3, 4, 5, 6, 8][(d - E).days]
        return None
    sun = week_sunday(d)
    P = _paschal_year_start(sun)
    thomas = P + td(days=7)
    if sun < thomas:
        P = easter(P.year - 1)
        thomas = P + td(days=7)
    weeks = (sun - thomas).days // 7
    return weeks % 8 + 1


def eothinon(d):
    """Εωθινό Ευαγγέλιο της Κυριακής (1-11) ή None."""
    if d.weekday() != 6:
        return None
    E = easter(d.year)
    special = {7: 1, 14: 3, 21: 4, 28: 7, 35: 8, 42: 10, 49: 9}
    k = (d - E).days
    if k in special:
        return special[k]
    if -7 <= k <= 55:
        return None
    allsaints = E + td(days=56)
    if d < allsaints:
        allsaints = easter(d.year - 1) + td(days=56)
    return ((d - allsaints).days // 7) % 11 + 1


def sunday_after_pentecost(d):
    """Αριθμός Κυριακής μετά την Πεντηκοστή (Α΄ = Αγίων Πάντων) ή None."""
    if d.weekday() != 6:
        return None
    E = easter(d.year)
    pent = E + td(days=49)
    if d <= pent:
        pent = easter(d.year - 1) + td(days=49)
        if d >= easter(d.year) - td(days=70):
            return None
    n = (d - pent).days // 7
    return n if n >= 1 else None


def period(d):
    E = easter(d.year)
    k = (d - E).days
    if -70 <= k <= -1:
        return "Τριώδιο" + (" · Μεγάλη Τεσσαρακοστή" if -48 <= k <= -9 else (" · Μεγάλη Εβδομάδα" if k >= -7 else ""))
    if 0 <= k <= 56:
        return "Πεντηκοστάριο"
    return "Οκτώηχος"


def movable(d):
    k = (d - easter(d.year)).days
